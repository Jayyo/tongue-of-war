#!/usr/bin/env python3
"""Slice a 4x3 character parts sheet into individual rig parts + a manifest.

The sheet is generated by tools/gen-parts.mjs with one body part per cell on a
#00FF00 chroma field. This script:

  1. cuts each cell,
  2. removes the chroma (same despill logic as cut-chroma.py),
  3. tightens to the part's real bounds,
  4. records a PIVOT for each part — the joint it rotates about.

The pivot is the whole point. A forearm must rotate about its elbow, not about
its image centre, or the arm detaches when it bends. Pivots are expressed as
fractions of the trimmed part so they survive any later resize.

    python3 tools/slice-parts.py human-artillery
"""
import json
import sys
import pathlib
import numpy as np
from PIL import Image, ImageFilter

ROOT = pathlib.Path(__file__).resolve().parent.parent
RAW = ROOT / "assets" / "unit-parts" / "raw"
OUT = ROOT / "assets" / "unit-parts"

COLS, ROWS = 4, 3
NEAR, FAR = 0.34, 0.70

# Cell order must match gen-parts.mjs CELLS exactly.
# pivot: where this part attaches to its PARENT, as (x, y) fractions of the
# trimmed image. y=0 is the top of the part.
PARTS = [
    # name,          parent,        pivot(x,y),  z-order
    ("head",         "torso",       (0.44, 0.86), 3),
    ("torso",        "pelvis",      (0.50, 0.94), 2),
    ("pelvis",       None,          (0.50, 0.35), 1),
    ("frontUpper",   "torso",       (0.50, 0.10), 5),   # shoulder at the top
    ("frontFore",    "frontUpper",  (0.50, 0.08), 6),   # elbow at the top
    ("backUpper",    "torso",       (0.50, 0.10), -2),
    ("backFore",     "backUpper",   (0.50, 0.08), -1),
    ("frontThigh",   "pelvis",      (0.50, 0.08), 4),
    ("frontShin",    "frontThigh",  (0.50, 0.06), 4),
    ("backThigh",    "pelvis",      (0.50, 0.08), -3),
    ("backShin",     "backThigh",   (0.50, 0.06), -3),
    ("_empty",       None,          (0.5, 0.5),   0),
]


def chroma_alpha(rgb: np.ndarray) -> np.ndarray:
    r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
    d = 1.0 - np.clip(g - np.maximum(r, b), 0.0, 1.0)
    a = np.clip((d - NEAR) / (FAR - NEAR), 0.0, 1.0)
    a = np.asarray(
        Image.fromarray((a * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.0))
    ).astype(np.float32) / 255.0
    return a


def despill(rgb: np.ndarray, a: np.ndarray) -> np.ndarray:
    out = rgb.copy()
    r, g, b = out[..., 0], out[..., 1], out[..., 2]
    spill = np.clip(g - np.maximum(r, b), 0.0, 1.0)
    edge = (a > 0.02) & (a < 0.995)
    out[..., 1] = np.where(edge, g - spill * 0.9, g)
    return np.clip(out, 0.0, 1.0)


def main() -> None:
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    unit = sys.argv[1]
    src = RAW / f"{unit}.png"
    if not src.exists():
        print(f"missing {src}")
        sys.exit(1)

    sheet = Image.open(src).convert("RGB")
    W, H = sheet.size
    cw, ch = W // COLS, H // ROWS

    dst = OUT / unit
    dst.mkdir(parents=True, exist_ok=True)
    manifest = {"unit": unit, "parts": {}}

    for i, (name, parent, pivot, z) in enumerate(PARTS):
        if name == "_empty":
            continue
        cx, cy = (i % COLS) * cw, (i // COLS) * ch
        cell = sheet.crop((cx, cy, cx + cw, cy + ch))
        rgb = np.asarray(cell).astype(np.float32) / 255.0
        a = chroma_alpha(rgb)
        if a.max() < 0.2:
            print(f"  {name}: EMPTY CELL — skipped")
            continue
        rgb = despill(rgb, a)
        im = Image.fromarray((np.dstack([rgb, a]) * 255).astype(np.uint8), "RGBA")
        bbox = Image.fromarray((a > 0.15).astype(np.uint8) * 255).getbbox()
        if bbox:
            im = im.crop(bbox)
        im.save(dst / f"{name}.png")
        manifest["parts"][name] = {
            "file": f"{name}.png",
            "w": im.width,
            "h": im.height,
            "parent": parent,
            "pivot": list(pivot),
            "z": z,
        }
        print(f"  {name}: {im.width}x{im.height}  parent={parent}  z={z}")

    (dst / "rig.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False))
    print(f"\n{unit}: {len(manifest['parts'])} parts -> {dst}/rig.json")


if __name__ == "__main__":
    main()
